// Single source of truth: version.json. Usage: node scripts/build.mjs [--bump patch|minor|major|none]
// Writes public/version.js (app + service worker), src/version.js (Worker /api/version),
// and renders templates/index.html + templates/sw.js into public/ with the version stamped in.
import fs from 'node:fs';
const arg = process.argv.indexOf('--bump'); const bump = arg > -1 ? process.argv[arg + 1] : 'none';
const vf = JSON.parse(fs.readFileSync('version.json', 'utf8'));
let [ma, mi, pa] = vf.version.split('.').map(Number);
if (bump === 'major') { ma++; mi = 0; pa = 0; } else if (bump === 'minor') { mi++; pa = 0; } else if (bump === 'patch') pa++;
const version = `${ma}.${mi}.${pa}`;
// Reproducible builds: the build time comes from version.json (set on bump), so a plain build changes nothing.
const built = bump === 'none' && vf.built ? vf.built : new Date().toISOString();
const info = { version, built };
fs.writeFileSync('version.json', JSON.stringify({ version, built }, null, 2) + '\n');
fs.writeFileSync('public/version.js', `self.HH_VERSION = ${JSON.stringify(info)};\n`);
fs.writeFileSync('src/version.js', `// generated by scripts/build.mjs\nexport const VERSION_INFO = ${JSON.stringify(info)};\n`);
for (const f of ['index.html', 'sw.js', 'setup.html']) fs.writeFileSync(`public/${f}`, fs.readFileSync(`templates/${f}`, 'utf8').replaceAll('__V__', version));
console.log(JSON.stringify(info));
